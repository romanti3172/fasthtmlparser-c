"""Writes the generated tables of the library from the generated tables of the Rust port (themselves written from
the Go port, which is generated from the C# sources) and from Python's unicodedata:

- include/fasthtmlparser_names.h: the FHP_TAG_* constants and the FHP_ATTR_* attribute names
- src/tables_gen.c: tag names and their hash table, the HTML5 optional-end-tag rules, void / raw-text / line-break
  tables and the HTML5 named character references
- src/unicode_gen.c: White_Space, letters and digits (XPath names), lower / upper case mappings

    python tools/gen.py ../fasthtmlparser-rs
"""

import re
import sys
import unicodedata
from pathlib import Path

HEADER = "/* Code generated by tools/gen.py; DO NOT EDIT. */\n\n"


def rust_string(literal: str) -> str:
    """Decodes a Rust string literal body (without the quotes)."""
    out = []
    i = 0
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        e = literal[i + 1]
        if e == "u":
            end = literal.index("}", i)
            out.append(chr(int(literal[i + 3 : end], 16)))
            i = end + 1
        else:
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'", "0": "\0"}[e])
            i += 2
    return "".join(out)


def c_string(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F and chr(b) != "?":
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def fnv(name: bytes) -> int:
    h = 2166136261
    for b in name:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


TAG_HASH_SIZE = 1024


def load_tags(rs: Path):
    text = (rs / "src" / "names.rs").read_text(encoding="utf-8")
    consts = re.findall(r"pub const (\w+): Tag = Tag\((\d+)\);", text)
    body = text[text.index("TAG_NAMES") :]
    names = [rust_string(s) for s in re.findall(r'^    "((?:[^"\\]|\\.)*)",$', body, re.M)]
    assert len(consts) == len(names)
    for i, (_, n) in enumerate(consts):
        assert int(n) == i
    return [c for c, _ in consts], names


def names_header(consts, names, attrs) -> str:
    b = [HEADER, "#ifndef FASTHTMLPARSER_NAMES_H\n#define FASTHTMLPARSER_NAMES_H\n\n"]
    b.append("/* Known tag names: HTML (incl. obsolete), SVG, MathML and common XML (RSS, Atom, sitemap).\n")
    b.append("   Any other name works as a string. FHP_TAG_NONE (0): a name that is not in the list. */\n")
    b.append("enum fhp_tag {\n    FHP_TAG_NONE = 0,\n")
    for i, (c, n) in enumerate(zip(consts, names)):
        b.append(f"    FHP_TAG_{c} = {i + 1}, /* {n} */\n")
    b.append(f"    FHP_TAG_MAX = {len(names)}\n}};\n\n")
    b.append("/* Common HTML / SVG / XML attribute names; any other name works as a plain string. */\n")
    for c, v in attrs:
        b.append(f"#define FHP_ATTR_{c} {c_string(v)}\n")
    b.append("\n#endif\n")
    return "".join(b)


def load_attrs(rs: Path):
    text = (rs / "src" / "attr_names.rs").read_text(encoding="utf-8")
    return [(c, rust_string(v)) for c, v in re.findall(r'pub const (\w+): &str = "((?:[^"\\]|\\.)*)";', text)]


def load_entities(rs: Path):
    text = (rs / "src" / "entities.rs").read_text(encoding="utf-8")
    rows = re.findall(r'^    \("(\w+)", "((?:[^"\\]|\\.)*)", (true|false)\),$', text, re.M)
    max_name = int(re.search(r"ENTITY_MAX_NAME: usize = (\d+)", text).group(1))
    max_legacy = int(re.search(r"ENTITY_MAX_LEGACY_NAME: usize = (\d+)", text).group(1))
    rows = [(n, rust_string(v), legacy == "true") for n, v, legacy in rows]
    rows.sort(key=lambda r: r[0].encode())
    return rows, max_name, max_legacy


def tables(consts, names, entities, max_name, max_legacy) -> str:
    idx = {n: i for i, n in enumerate(names)}
    count = len(names)

    def t(*ns):
        return [idx[n] for n in ns]

    scope_stops = t("html", "body", "table", "caption", "td", "th", "template", "object", "applet", "marquee", "button")
    table_stops = t("html", "body", "template", "table")
    select_stops = t("html", "body", "template", "select", "datalist")
    # (targets, stops, the tags the rule applies on)
    rules = [
        (t("li"), scope_stops + t("ul", "ol", "menu"), t("li")),
        (t("dt", "dd"), scope_stops + t("dl"), t("dt", "dd")),
        (t("td", "th"), table_stops + t("tr", "tbody", "thead", "tfoot"), t("td", "th")),
        (t("tr", "td", "th"), table_stops + t("tbody", "thead", "tfoot"), t("tr")),
        (t("tbody", "thead", "tfoot", "tr", "td", "th", "caption"), table_stops, t("tbody", "thead", "tfoot")),
        (t("option"), select_stops + t("optgroup"), t("option")),
        (t("option", "optgroup"), select_stops, t("optgroup")),
        (t("p"), scope_stops, []),  # <p> is ended by the start of a block element
    ]
    p_rule = len(rules) - 1
    implied = [-1] * count
    for r, (_, _, on) in enumerate(rules):
        for k in on:
            implied[k] = r
    rule_target = [False] * count
    for r in set(x for x in implied if x >= 0):
        for k in rules[r][0]:
            rule_target[k] = True
    closes_p = set(t("address", "article", "aside", "blockquote", "center", "details", "dialog", "dir", "div", "dl",
                     "fieldset", "figcaption", "figure", "footer", "form", "h1", "h2", "h3", "h4", "h5", "h6", "header",
                     "hgroup", "hr", "listing", "main", "menu", "nav", "ol", "p", "pre", "search", "section",
                     "summary", "table", "ul", "li", "dd", "dt", "plaintext", "xmp"))
    void = set(t("area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr",
                 "basefont", "bgsound", "frame", "keygen", "param", "isindex", "!doctype", "?xml"))
    raw = set(t("script", "style", "textarea", "title", "xmp", "iframe", "noembed", "noframes"))

    # line-break kinds: 0 none, 1 space, 2 line, 3 paragraph, 4 skip content
    lb = [0] * count
    for k in t("p", "h1", "h2", "h3", "h4", "h5", "h6"):
        lb[k] = 3
    for k in t("br", "div", "li", "ul", "ol", "dl", "dt", "dd", "table", "caption", "tr", "thead", "tbody", "tfoot",
               "section", "article", "aside", "nav", "header", "footer", "main", "address", "blockquote", "pre", "hr",
               "figure", "figcaption", "form", "fieldset", "legend", "details", "summary", "dialog", "option", "html",
               "head", "body", "title", "hgroup", "search", "menu", "center", "dir", "listing", "xmp", "plaintext",
               "multicol", "frameset", "marquee"):
        lb[k] = 2
    for k in t("td", "th"):
        lb[k] = 1
    for k in t("script", "style", "noscript", "template", "noframes", "noembed"):
        lb[k] = 4

    b = [HEADER, '#include "internal.h"\n\n']
    b.append("const char *const fhp_tag_names[FHP_TAG_COUNT] = {\n")
    for n in names:
        b.append(f"    {c_string(n)},\n")
    b.append("};\n\nconst unsigned char fhp_tag_name_lens[FHP_TAG_COUNT] = {\n")
    for i in range(0, count, 16):
        b.append("    " + ", ".join(str(len(n.encode())) for n in names[i : i + 16]) + ",\n")
    b.append("};\n\n")

    slots = [-1] * TAG_HASH_SIZE
    for i, n in enumerate(names):
        h = fnv(n.encode()) & (TAG_HASH_SIZE - 1)
        while slots[h] >= 0:
            h = (h + 1) & (TAG_HASH_SIZE - 1)
        slots[h] = i
    b.append(f"/* open addressing on FNV-1a of the lower-case name */\nconst short fhp_tag_hash[{TAG_HASH_SIZE}] = {{\n")
    for i in range(0, TAG_HASH_SIZE, 16):
        b.append("    " + ", ".join(str(x) for x in slots[i : i + 16]) + ",\n")
    b.append("};\n\n")

    def flags(i):
        f = []
        if i in void:
            f.append("FHP_F_VOID")
        if i in closes_p:
            f.append("FHP_F_CLOSES_P")
        if rule_target[i]:
            f.append("FHP_F_RULE_TARGET")
        if i in raw:
            f.append("FHP_F_RAW_TEXT")
        return "|".join(f) or "0"

    b.append("const unsigned char fhp_tag_flags[FHP_TAG_COUNT] = {\n")
    for i, n in enumerate(names):
        b.append(f"    {flags(i)}, /* {n} */\n")
    b.append("};\n\nconst signed char fhp_tag_rule[FHP_TAG_COUNT] = {\n")
    for i in range(0, count, 16):
        b.append("    " + ", ".join(str(x) for x in implied[i : i + 16]) + ",\n")
    b.append("};\n\nconst unsigned char fhp_tag_line_break[FHP_TAG_COUNT] = {\n")
    for i in range(0, count, 16):
        b.append("    " + ", ".join(str(x) for x in lb[i : i + 16]) + ",\n")
    b.append("};\n\n")

    b.append(f"const fhp_rule fhp_rules[FHP_RULE_COUNT] = {{\n")
    for targets, stops, _ in rules:
        tset = set(targets)
        sset = set(stops)
        b.append("    {{" + ", ".join(str(k) for k in targets) + f"}}, {len(targets)},\n     {{")
        b.append(", ".join("1" if i in tset else "0" for i in range(count)))
        b.append("},\n     {")
        b.append(", ".join("1" if i in sset else "0" for i in range(count)))
        b.append("}},\n")
    b.append("};\n\n")

    b.append(f"const fhp_entity fhp_entities[FHP_ENTITY_COUNT] = {{\n")
    for name, value, legacy in entities:
        b.append(f"    {{{c_string(name)}, {c_string(value)}, {len(name)}, {len(value.encode())}, {int(legacy)}}},\n")
    b.append("};\n")

    defs = (
        f"#define FHP_TAG_COUNT {count}\n"
        f"#define FHP_TAG_HASH_SIZE {TAG_HASH_SIZE}\n"
        f"#define FHP_RULE_COUNT {len(rules)}\n"
        f"#define FHP_P_RULE {p_rule}\n"
        f"#define FHP_ENTITY_COUNT {len(entities)}\n"
        f"#define FHP_ENTITY_MAX_NAME {max_name}\n"
        f"#define FHP_ENTITY_MAX_LEGACY_NAME {max_legacy}\n"
        f"#define FHP_MAX_RULE_TARGETS {max(len(r[0]) for r in rules)}\n"
    )
    return "".join(b), defs


def ranges(pred):
    out = []
    start = None
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def unicode_tables() -> str:
    b = [HEADER, '#include "internal.h"\n\n']

    def emit_ranges(name, rs):
        b.append(f"const unsigned fhp_{name}_ranges[][2] = {{\n")
        for lo, hi in rs:
            b.append(f"    {{0x{lo:X}, 0x{hi:X}}},\n")
        b.append(f"}};\nconst size_t fhp_{name}_count = {len(rs)};\n\n")

    emit_ranges("alpha", ranges(lambda c: unicodedata.category(c)[0] == "L" or unicodedata.category(c) == "Nl"))
    emit_ranges("numeric", ranges(lambda c: unicodedata.category(c) in ("Nd", "Nl", "No")))

    def emit_map(name, f):
        rows = []
        for cp in range(0x80, 0x110000):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            m = f(chr(cp))
            if m != chr(cp):
                rows.append((cp, m))
        b.append(f"const fhp_case_map fhp_{name}_map[] = {{\n")
        for cp, m in rows:
            b.append(f"    {{0x{cp:X}, {c_string(m)}}},\n")
        b.append(f"}};\nconst size_t fhp_{name}_count = {len(rows)};\n\n")

    emit_map("lower", lambda c: c.lower())
    emit_map("upper", lambda c: c.upper())
    return "".join(b)


def main() -> None:
    rs = Path(sys.argv[1] if len(sys.argv) > 1 else "../fasthtmlparser-rs")
    root = Path(__file__).resolve().parent.parent
    consts, names = load_tags(rs)
    attrs = load_attrs(rs)
    entities, max_name, max_legacy = load_entities(rs)
    table_src, defs = tables(consts, names, entities, max_name, max_legacy)
    outputs = {
        root / "include" / "fasthtmlparser_names.h": names_header(consts, names, attrs),
        root / "src" / "tables_gen.c": table_src,
        root / "src" / "tables_gen.h": HEADER + "#ifndef FHP_TABLES_GEN_H\n#define FHP_TABLES_GEN_H\n\n" + defs + "\n#endif\n",
        root / "src" / "unicode_gen.c": unicode_tables(),
    }
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
